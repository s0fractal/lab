#!/usr/bin/env python3
"""S3 calibration (exploration): seeds 100+, tasks A and B at T = 32, the same budget of configurations for every
model. Every job is appended to calibration/trials.jsonl as it finishes, winners and losers alike; nothing here
reads a test cell (per-sigma cells come from the "calib" namespace).

    .venv/bin/python tools/calibrate.py run calibration/rounds/round-1.json [--workers 12]
    .venv/bin/python tools/calibrate.py summary            # writes calibration/SUMMARY.md

A round file lists trials {id, kind, cfg (overrides of the model defaults), rationale}; a trial is one configuration
trained on both tasks with the calibration seed. Shared settings live in calibration/shared.json and are fixed before
the first trial.
"""
from __future__ import annotations

import json
import multiprocessing as mp
import subprocess
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from phs import tasks  # noqa: E402
from phs.models import build, count_params  # noqa: E402

CAL = ROOT / "calibration"
TRIALS = CAL / "trials.jsonl"
BUDGET = 12


def shared() -> dict:
    return json.loads((CAL / "shared.json").read_text())


def job_config(kind: str, task: str, overrides: dict, sh: dict) -> dict:
    cfg = dict(sh["model_defaults"])
    cfg.update(sh["optimisation"])
    cfg.update(overrides)
    if kind == "gru_pm":
        spec = tasks.TASKS[task]
        sol = dict(cfg, N=cfg["N"], d=cfg["d"])
        import torch
        cfg["pm_target"] = count_params(build("soliton", spec["vocab"], spec["classes"], sol, torch.Generator()))
    return cfg


def work(args):
    trial, task, cfg, sh = args
    from phs.train import run, setup_determinism
    setup_determinism(1)
    rec = run(trial["kind"], task, sh["T"], sh["seed"], cfg, n_test=sh["n_cells"], namespace="calib")
    rec.pop("cfg", None)
    return {"trial": trial["id"], "round": trial["round"], "kind": trial["kind"], "task": task,
            "overrides": trial["cfg"], "rationale": trial["rationale"], "cfg": cfg, "commit": sh.get("commit"), **rec}


def done_jobs() -> set:
    if not TRIALS.exists():
        return set()
    return {(r["trial"], r["task"]) for r in map(json.loads, TRIALS.read_text().splitlines())}


def cmd_run(round_file: Path, workers: int) -> int:
    sh = shared()
    spec = json.loads(round_file.read_text())
    seen = {}
    for r in map(json.loads, TRIALS.read_text().splitlines()) if TRIALS.exists() else []:
        seen.setdefault(r["kind"], set()).add(r["trial"])
    jobs = []
    have = done_jobs()
    for trial in spec["trials"]:
        trial = dict(trial, round=spec["round"])
        ids = seen.setdefault(trial["kind"], set())
        ids.add(trial["id"])
        if len(ids) > BUDGET:
            print(f"refused: {trial['kind']} would exceed the budget of {BUDGET} configurations")
            return 2
        for task in ("A", "B"):
            if (trial["id"], task) not in have:
                jobs.append((trial, task, job_config(trial["kind"], task, trial["cfg"], sh), sh))
    head = subprocess.run(["git", "rev-parse", "HEAD"], cwd=ROOT, capture_output=True, text=True).stdout.strip()
    dirty = subprocess.run(["git", "status", "--porcelain", "--", "phs", "tools"], cwd=ROOT, capture_output=True,
                           text=True).stdout.strip()
    if dirty:
        print(f"refused: uncommitted changes in phs/ or tools/; a round runs from a commit\n{dirty}")
        return 2
    jobs = [(t, task, cfg, dict(sh, commit=head)) for t, task, cfg, sh in jobs]
    print(f"round {spec['round']}: {len(jobs)} jobs, {workers} workers, commit {head}", flush=True)
    t0 = time.time()
    ctx = mp.get_context("spawn")
    with ctx.Pool(workers, maxtasksperchild=1) as pool:
        for rec in pool.imap_unordered(work, jobs):
            with TRIALS.open("a") as f:
                f.write(json.dumps(rec, sort_keys=True) + "\n")
            print(f"[{time.time() - t0:6.0f}s] {rec['trial']} {rec['task']}: {rec['status']} "
                  f"val {rec.get('best_val_acc', float('nan')):.4f} wall {rec.get('wall_seconds', 0):.0f}s "
                  f"rss {rec['peak_rss_bytes'] / 2**20:.0f}MB", flush=True)
    return 0


def select(scored: list):
    """Highest objective; within 0.01 of it, the lowest mean validation loss."""
    if not scored:
        return None
    top = max(o for _, o, _ in scored)
    return min((x for x in scored if x[1] >= top - 0.01), key=lambda x: (x[2], x[0]))


def cmd_summary() -> int:
    rows = [json.loads(line) for line in TRIALS.read_text().splitlines()]
    by = {}
    for r in rows:
        by.setdefault((r["kind"], r["trial"]), {})[r["task"]] = r
    out = ["# Calibration trials", "",
           "Generated by `tools/calibrate.py summary` from `trials.jsonl` (every job, in order of completion). "
           "Objective: mean over tasks A and B of the best validation accuracy (validation sigma drawn uniformly "
           "from the grid), T = 32, seed 100. Selection (fixed after round 1, before round 2): the highest "
           "objective; configurations within 0.01 of it are tied and the tie goes to the lower mean best validation "
           "loss over A and B. Per-sigma columns read the `calib` cells (1024 sequences), never the test cells. "
           "Round 1 ran from commit f246d4b (records of later rounds carry their commit).", ""]
    for kind in ("pure", "soliton", "gru", "gru_pm"):
        trials = [(t, v) for (k, t), v in by.items() if k == kind]
        if not trials:
            continue
        out += [f"## {kind} ({len(trials)} of {BUDGET} configurations)", "",
                "| trial | round | overrides | val A | val B | objective | A acc by sigma 0.00..0.35 | B acc sigma 0 | "
                "status | params | wall s (A/B) | peak RSS MB |",
                "|---|---|---|---|---|---|---|---|---|---|---|---|"]
        scored = []
        for t, v in trials:
            a, b = v.get("A"), v.get("B")
            va = a.get("best_val_acc") if a else None
            vb = b.get("best_val_acc") if b else None
            obj = (va + vb) / 2 if va is not None and vb is not None else None
            if obj is not None:
                scored.append((t, obj, (a["best_val_loss"] + b["best_val_loss"]) / 2))
            sig = " ".join(f"{c['acc']:.2f}" for c in a["cells"].values()) if a and "cells" in a else "-"
            b0 = f"{b['cells']['0.00']['acc']:.3f}" if b and "cells" in b else "-"
            st = "/".join(x["status"] for x in (a, b) if x)
            wall = "/".join(f"{x.get('wall_seconds', 0):.0f}" for x in (a, b) if x)
            rss = max(x["peak_rss_bytes"] for x in (a, b) if x) / 2 ** 20
            params = "/".join(str(x["params"]) for x in (a, b) if x)
            fmt = lambda z: "-" if z is None else f"{z:.4f}"
            out.append(f"| {t} | {(a or b)['round']} | `{json.dumps((a or b)['overrides'], sort_keys=True)}` | "
                       f"{fmt(va)} | {fmt(vb)} | {fmt(obj)} | {sig} | {b0} | {st} | {params} | {wall} | {rss:.0f} |")
        best = select(scored)
        out += ["", f"Selected so far: {best[0]} (objective {best[1]:.4f}, mean val loss {best[2]:.4f})."
                if best else "No complete trial.", ""]
        out += ["Rationales:", ""] + [f"- {t}: {(v.get('A') or v.get('B'))['rationale']}" for t, v in trials] + [""]
    (CAL / "SUMMARY.md").write_text("\n".join(out))
    print("\n".join(out))
    return 0


def main(argv: list[str]) -> int:
    if argv[:1] == ["run"]:
        workers = int(argv[argv.index("--workers") + 1]) if "--workers" in argv else 1
        return cmd_run(Path(argv[1]), workers)
    if argv[:1] == ["summary"]:
        return cmd_summary()
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
